import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync, spawnSync } from 'node:child_process';
import { spawn } from 'node:child_process';
import http from 'node:http';
import { startServer, stopServer } from './test-server.mjs';

test('each bot sees only its own room and wiki captures wait for engagement', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'todos-bot-'));
  const provision = spawnSync('node', ['scripts/provision-bots.mjs'], { env: { ...process.env, DATA_DIR: dir, TODOS_USER: 'owner' }, encoding: 'utf8' });
  assert.equal(provision.status, 0, provision.stderr);
  const server = await startServer('server.js', { env: { DATA_DIR: dir, TODOS_USER: 'owner', TODOS_PASS: 'fixture-password', API_TOKEN: 'fixture-api' } });
  t.after(async () => { await stopServer(server.child); fs.rmSync(dir, { recursive: true, force: true }); });
  const bots = Object.fromEntries(['sherlock', 'claw', 'lurch'].map(name => [name, fs.readFileSync(path.join(dir, 'bot-credentials', name), 'utf8').trim()]));
  const accounts = JSON.parse(fs.readFileSync(path.join(dir, 'accounts.json')));
  const request = async (bot, route, body, room) => {
    const res = await fetch(server.base + route, { method: body ? 'POST' : 'GET', headers: { Authorization: `Bearer ${bots[bot]}`, ...(body ? { 'Content-Type': 'application/json' } : {}), ...(room ? { 'X-Todos-Room': room } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: res.status, body: await res.json() };
  };
  const shRoom = accounts.bots.sherlock.room, clawRoom = accounts.bots.claw.room;
  assert.notEqual(shRoom, clawRoom);
  assert.equal((await request('sherlock', '/kanban/external/card', { key: 'wiki:a', title: 'Reference', kind: 'todo' })).status, 200);
  assert.equal((await request('claw', '/kanban/external/card', { key: 'claw:a', title: 'Investigate', kind: 'todo' })).status, 200);
  const sh = (await request('sherlock', '/kanban/external/cards')).body.cards;
  assert.equal(sh.length, 1); assert.equal(sh[0].status, 'todo'); assert.notEqual(sh[0].kind, 'note');
  assert.equal((await request('sherlock', '/kanban/external/cards', null, clawRoom)).status, 403);
  assert.equal((await request('claw', '/kanban/external/cards', null, 'personal')).status, 403);
  assert.equal((await request('lurch', '/kanban/external/cards')).body.cards.length, 0);
  assert.equal((await fetch(server.base + '/kanban/snapshot', { headers: { Authorization: `Bearer ${bots.sherlock}` } })).status, 403);
  const login = await fetch(server.base + '/kanban/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'owner', password: 'fixture-password' }) });
  const cookie = login.headers.getSetCookie()[0].split(';')[0];
  const info = await (await fetch(server.base + '/kanban/account', { headers: { cookie } })).json();
  assert.deepEqual(info.rooms.filter(r => r.bot).map(r => r.bot).sort(), ['claw', 'lurch', 'sherlock']);
  const personal = await (await fetch(server.base + '/kanban/snapshot', { headers: { cookie } })).json();
  assert.equal(personal.cards.length, 0);
  const source = await fetch(server.base + '/kanban/external/card', { method: 'POST', headers: { Authorization: 'Bearer fixture-api', 'Content-Type': 'application/json' }, body: JSON.stringify({ key: 'owner:source', title: 'Plan the next step', notes: 'Private context', kind: 'note' }) });
  const sourceId = (await source.json()).id;
  const firstCardId = (await request('claw', '/kanban/external/cards')).body.cards[0].id;
  const askBody = { bot: 'claw', id: firstCardId, message: 'Investigate the options.', requestId: 'ask-claw-first-01' };
  const askFrom = (room, body) => fetch(`${server.base}/kanban/bots/ask?room=${encodeURIComponent(room)}`, { method: 'POST', headers: { cookie, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal((await askFrom('personal', { ...askBody, id: sourceId })).status, 403);
  assert.equal((await askFrom(shRoom, { ...askBody, id: sh[0].id })).status, 403);
  assert.equal((await askFrom(clawRoom, { ...askBody, bot: 'lurch' })).status, 403);
  assert.equal((await fetch(`${server.base}/kanban/bots/delegate?room=${encodeURIComponent(clawRoom)}`, { method: 'POST', headers: { cookie } })).status, 410);
  const firstAsk = await (await askFrom(clawRoom, askBody)).json();
  assert.equal(firstAsk.requests.length, 1);
  assert.equal((await (await askFrom(clawRoom, askBody)).json()).requests.length, 1);
  assert.equal((await request('claw', '/kanban/external/cards')).body.cards.length, 1);
  const ownerBoard = await (await fetch(server.base + '/kanban/snapshot', { headers: { cookie } })).json();
  assert.equal(ownerBoard.cards.length, 1);
  const delivered = [];
  const hook = http.createServer(async (req, res) => {
    let raw = ''; for await (const chunk of req) raw += chunk;
    delivered.push(JSON.parse(raw));
    res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify({ status: 'accepted' }));
  });
  await new Promise(resolve => hook.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => hook.close(resolve)));
  const secretFile = path.join(dir, 'hook-secret'); fs.writeFileSync(secretFile, 'fixture-secret');
  const jobsFile = path.join(dir, 'claw-jobs.json');
  fs.writeFileSync(jobsFile, JSON.stringify({ jobs: [{ id: 'regular01', name: 'Daily check', enabled: true, schedule: { display: '0 9 * * *' }, next_run_at: '2030-01-01T09:00:00Z' }] }));
  const worker = spawn('node', ['scripts/dispatch-bot.mjs'], { env: { ...process.env, BOT_NAME: 'claw', BOT_ROOM_ID: clawRoom, BOT_TOKEN_FILE: path.join(dir, 'bot-credentials/claw'), BOT_WEBHOOK_SECRET_FILE: secretFile, BOT_WEBHOOK_URL: `http://127.0.0.1:${hook.address().port}/hook`, BOT_JOBS_FILE: jobsFile, TODOS_BASE: server.base } });
  const code = await new Promise(resolve => worker.on('exit', resolve));
  assert.equal(code, 0);
  assert.equal(delivered.length, 1);
  assert.match(delivered[0].prompt, /Investigate the options/);
  assert.match(delivered[0].prompt, /same card/);
  assert.equal((await request('claw', `/kanban/external/card?id=${firstCardId}`)).body.card.status, 'todo');
  const reply = await request('claw', '/kanban/external/ask/reply', { requestId: askBody.requestId, status: 'done', reply: 'The options are A and B.' });
  assert.equal(reply.status, 200);
  const conversation = await (await fetch(`${server.base}/kanban/bots/conversation?room=${encodeURIComponent(clawRoom)}&id=${encodeURIComponent(firstCardId)}`, { headers: { cookie } })).json();
  assert.equal(conversation.requests[0].reply, 'The options are A and B.');
  const snapshot = async room => (await (await fetch(`${server.base}/kanban/snapshot?room=${encodeURIComponent(room)}`, { headers: { cookie } })).json());
  const view = async (room, id, through) => (await fetch(`${server.base}/kanban/bots/conversation/view?room=${encodeURIComponent(room)}`, { method: 'POST', headers: { cookie, 'Content-Type': 'application/json' }, body: JSON.stringify({ id, through }) })).json();
  let board = await snapshot(clawRoom);
  assert.equal(board.labels.find(label => label.id === 'claw:replied')?.removeOnView, true);
  assert.ok(board.cards.find(card => card.id === firstCardId).labels.includes('claw:replied'));
  const again = { bot: 'claw', id: firstCardId, message: 'One more question.', requestId: 'ask-claw-second-01' };
  assert.equal((await askFrom(clawRoom, again)).status, 200);
  assert.equal((await request('claw', '/kanban/external/ask/reply', { requestId: again.requestId, status: 'done', reply: 'Second answer.' })).status, 200);
  await view(clawRoom, firstCardId, askBody.requestId);
  board = await snapshot(clawRoom);
  assert.ok(board.cards.find(card => card.id === firstCardId).labels.includes('claw:replied'));
  await view(clawRoom, firstCardId, again.requestId);
  board = await snapshot(clawRoom);
  assert.equal(board.cards.find(card => card.id === firstCardId).labels.includes('claw:replied'), false);
  const lurchCard = (await request('lurch', '/kanban/external/card', { key: 'lurch:reply-label', title: 'Lurch check', kind: 'todo' })).body;
  const lurchAsk = { bot: 'lurch', id: lurchCard.id, message: 'Check status.', requestId: 'ask-lurch-label-01' };
  assert.equal((await askFrom(accounts.bots.lurch.room, lurchAsk)).status, 200);
  assert.equal((await request('lurch', '/kanban/external/ask/reply', { requestId: lurchAsk.requestId, status: 'done', reply: 'Checked.' })).status, 200);
  board = await snapshot(accounts.bots.lurch.room);
  assert.equal(board.labels.find(label => label.id === 'lurch:replied')?.removeOnView, true);
  assert.ok(board.cards.find(card => card.id === lurchCard.id).labels.includes('lurch:replied'));
  await view(accounts.bots.lurch.room, lurchCard.id, lurchAsk.requestId);
  board = await snapshot(accounts.bots.lurch.room);
  assert.equal(board.cards.find(card => card.id === lurchCard.id).labels.includes('lurch:replied'), false);
  const schedule = (await request('claw', '/kanban/external/cards')).body.cards.find(c => c.key === 'cron:regular01');
  assert.equal(schedule.status, 'todo');
  const scheduledCard = (await request('claw', `/kanban/external/card?id=${schedule.id}`)).body.card;
  assert.equal(scheduledCard.notify, false);
  assert.equal(scheduledCard.remindAt, '2030-01-01T09:00:00.000Z');
  const scheduledAsk = await (await askFrom(clawRoom, { bot: 'claw', id: schedule.id, message: 'What happened on the last run?', requestId: 'ask-claw-scheduled-01' })).json();
  assert.equal(scheduledAsk.requests[0].status, 'queued');
  assert.equal((await request('claw', '/kanban/external/cards')).body.cards.length, 2);
  assert.equal((await request('claw', `/kanban/external/card?id=${schedule.id}`)).body.card.links.length, 0);
  const executionsFile = path.join(dir, 'executions.db');
  const sqlite = (sql) => execFileSync('python3', ['-c', 'import sqlite3,sys; db=sqlite3.connect(sys.argv[1]); db.executescript(sys.argv[2]); db.commit()', executionsFile, sql]);
  const runSync = async () => {
    const task = spawn('node', ['scripts/sync-bot-cron.mjs'], { env: { ...process.env, BOT_NAME: 'claw', BOT_TOKEN_FILE: path.join(dir, 'bot-credentials/claw'), BOT_JOBS_FILE: jobsFile, TODOS_BASE: server.base } });
    assert.equal(await new Promise(resolve => task.on('exit', resolve)), 0);
  };
  sqlite("CREATE TABLE executions (id TEXT, job_id TEXT, status TEXT, claimed_at TEXT, started_at TEXT, finished_at TEXT, error TEXT, delivery_outcome TEXT); INSERT INTO executions VALUES ('run1','regular01','running','2026-01-01T09:00:00Z','2026-01-01T09:00:01Z',NULL,NULL,NULL);");
  await runSync();
  assert.equal((await request('claw', `/kanban/external/card?id=${schedule.id}`)).body.card.status, 'doing');
  sqlite("UPDATE executions SET status='completed', finished_at='2026-01-01T09:02:00Z', delivery_outcome='delivered' WHERE id='run1';");
  fs.utimesSync(executionsFile, new Date('2030-01-02'), new Date('2030-01-02'));
  await runSync();
  const completedRun = (await request('claw', `/kanban/external/card?id=${schedule.id}`)).body.card;
  assert.equal(completedRun.status, 'todo');
  assert.match(completedRun.notes, /Outcome: Completed · delivered/);
  fs.writeFileSync(jobsFile, JSON.stringify({ jobs: [] }));
  fs.utimesSync(jobsFile, new Date('2031-01-01'), new Date('2031-01-01'));
  await runSync();
  assert.equal((await request('claw', `/kanban/external/card?id=${schedule.id}`)).status, 404);
  assert.equal((await request('sherlock', '/kanban/external/cards')).body.cards[0].status, 'todo');
  const legacy = await fetch(server.base + '/kanban/external/card', { method: 'POST', headers: { Authorization: 'Bearer fixture-api', 'Content-Type': 'application/json' }, body: JSON.stringify({ key: 'wiki:legacy', title: 'Older wiki brief', notes: 'Research summary', status: 'done' }) });
  const legacyId = (await legacy.json()).id;
  const migration = spawn('node', ['scripts/move-sherlock-wiki.mjs', '--apply'], { env: { ...process.env, DATA_DIR: dir, MIGRATION_API_TOKEN: 'fixture-api', TODOS_BASE: server.base } });
  let migrationLog = ''; migration.stdout.on('data', data => migrationLog += data); migration.stderr.on('data', data => migrationLog += data);
  assert.equal(await new Promise(resolve => migration.on('exit', resolve)), 0, migrationLog);
  assert.equal((await request('sherlock', `/kanban/external/card?id=${legacyId}`)).body.card.kind, 'note');
  assert.equal((await (await fetch(server.base + '/kanban/snapshot', { headers: { cookie } })).json()).cards.some(c => c.id === legacyId), false);
  const promotion = spawn('node', ['scripts/promote-sherlock-wiki.mjs', '--apply'], { env: { ...process.env, DATA_DIR: dir, MIGRATION_API_TOKEN: 'fixture-api', TODOS_BASE: server.base } });
  let promotionLog = ''; promotion.stdout.on('data', data => promotionLog += data); promotion.stderr.on('data', data => promotionLog += data);
  assert.equal(await new Promise(resolve => promotion.on('exit', resolve)), 0, promotionLog);
  assert.equal((await request('sherlock', `/kanban/external/card?id=${legacyId}`)).body.card.status, 'todo');
  assert.notEqual((await request('sherlock', `/kanban/external/card?id=${legacyId}`)).body.card.kind, 'note');
  const cliEnv = { ...process.env, BOT_TOKEN_FILE: path.join(dir, 'bot-credentials/sherlock'), TODOS_BASE: server.base };
  const started = spawnSync('node', ['scripts/bot-task.mjs', 'sherlock', 'start', 'Investigate a new lead', 'From a conversation'], { env: cliEnv, encoding: 'utf8' });
  assert.equal(started.status, 0, started.stderr);
  const workId = started.stdout.trim();
  assert.equal((await request('sherlock', `/kanban/external/card?id=${workId}`)).body.card.status, 'doing');
  const finished = spawnSync('node', ['scripts/bot-task.mjs', 'sherlock', 'done', workId, 'Found the answer'], { env: cliEnv, encoding: 'utf8' });
  assert.equal(finished.status, 0, finished.stderr);
  const work = (await request('sherlock', `/kanban/external/card?id=${workId}`)).body.card;
  assert.equal(work.status, 'done'); assert.match(work.notes, /Found the answer/);
  const sherlockWorker = spawn('node', ['scripts/dispatch-bot.mjs'], { env: { ...process.env, BOT_NAME: 'sherlock', BOT_ROOM_ID: shRoom, BOT_TOKEN_FILE: path.join(dir, 'bot-credentials/sherlock'), BOT_WEBHOOK_SECRET_FILE: secretFile, BOT_WEBHOOK_URL: `http://127.0.0.1:${hook.address().port}/hook`, TODOS_BASE: server.base } });
  assert.equal(await new Promise(resolve => sherlockWorker.on('exit', resolve)), 0);
  assert.equal(delivered.length, 1);
});

test('old queued Ask tasks move into the original card conversation on restart', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'todos-bot-ask-migrate-'));
  const setup = spawnSync('node', ['scripts/provision-bots.mjs'], { env: { ...process.env, DATA_DIR: dir, TODOS_USER: 'owner' }, encoding: 'utf8' });
  assert.equal(setup.status, 0, setup.stderr);
  const accounts = JSON.parse(fs.readFileSync(path.join(dir, 'accounts.json')));
  const room = accounts.bots.lurch.room;
  const token = fs.readFileSync(path.join(dir, 'bot-credentials/lurch'), 'utf8').trim();
  let server = await startServer('server.js', { env: { DATA_DIR: dir, TODOS_USER: 'owner', TODOS_PASS: 'fixture-password' } });
  t.after(async () => { await stopServer(server.child); fs.rmSync(dir, { recursive: true, force: true }); });
  const create = async body => {
    const res = await fetch(`${server.base}/kanban/external/card`, { method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    assert.equal(res.status, 200);
    return res.json();
  };
  const source = await create({ key: 'cron:old', title: 'Original card', notes: 'Scheduled work', kind: 'todo' });
  const old = await create({ key: 'delegate:old-request-01', title: 'Ask Lurch: Original card', notes: 'Is this duplicated?\n\nSource note: Original card\nScheduled work', links: [{ title: 'Source note', url: `https://todos.example/?room=${room}#card/${source.id}` }], kind: 'todo' });
  await stopServer(server.child);
  server = await startServer('server.js', { env: { DATA_DIR: dir, TODOS_USER: 'owner', TODOS_PASS: 'fixture-password' } });
  const login = await fetch(`${server.base}/kanban/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'owner', password: 'fixture-password' }) });
  const cookie = login.headers.getSetCookie()[0].split(';')[0];
  const conversation = await (await fetch(`${server.base}/kanban/bots/conversation?room=${room}&id=${source.id}`, { headers: { cookie } })).json();
  assert.equal(conversation.requests[0].message, 'Is this duplicated?');
  const cards = await (await fetch(`${server.base}/kanban/external/cards`, { headers: { Authorization: `Bearer ${token}` } })).json();
  assert.equal(cards.cards.some(card => card.id === old.id), false);
  assert.equal(cards.cards.some(card => card.id === source.id), true);
});
